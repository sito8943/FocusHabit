/**
 * Drop-in for Material's `Icon`: same parameters, a Font Awesome glyph inside.
 * 24dp unless [modifier] sets a size; tint follows the content colour.
 */
@Composable
fun FaIcon(
    name: String,
    contentDescription: String?,
    modifier: Modifier = Modifier,
    tint: Color = LocalContentColor.current,
) {
    val icon = FaIcons.find(name) ?: return
    BoxWithConstraints(
        modifier
            .then(Modifier.size(24.dp))
            .semantics {
                if (contentDescription != null) {
                    this.contentDescription = contentDescription
                    role = Role.Image
                }
            },
        contentAlignment = Alignment.Center,
    ) {
        FaGlyph(icon, tint, size = minOf(maxWidth, maxHeight) * 0.8f)
    }
}

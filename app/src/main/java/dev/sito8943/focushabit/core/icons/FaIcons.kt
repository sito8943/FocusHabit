data class FaIcon(val name: String, val glyph: String, val terms: String)

/**
 * Font Awesome 7 Free solid: the font plus `assets/fa_icons.json`
 * (`[name, unicodeHex, searchTerms]`, generated by tools/fontawesome). Loaded
 * on first use; ~1400 icons, a few ms.
 */
object FaIcons {

    val FontFamily = FontFamily(Font(R.font.fa_solid))

    /** Shown first in the picker: the usual habits. */
    val suggested = listOf(
        "droplet", "book-open", "person-running", "person-walking", "dumbbell", "bed",
        "spa", "brain", "apple-whole", "carrot", "mug-hot", "pills",
        "tooth", "pen-to-square", "graduation-cap", "language", "guitar", "seedling",
        "piggy-bank", "broom", "dog", "mobile-screen", "gamepad", "smoking",
    )

    private lateinit var appContext: Context

    fun init(context: Context) {
        appContext = context.applicationContext
    }

    val all: List<FaIcon> by lazy {
        val text = appContext.assets.open("fa_icons.json").bufferedReader().use { it.readText() }
        (Json.parseToJsonElement(text) as JsonArray).map { row ->
            val fields = row.jsonArray
            FaIcon(
                name = fields[0].jsonPrimitive.content,
                glyph = String(Character.toChars(fields[1].jsonPrimitive.content.toInt(16))),
                terms = fold(fields[2].jsonPrimitive.content),
            )
        }
    }

    private val byName: Map<String, FaIcon> by lazy { all.associateBy { it.name } }

    fun find(name: String?): FaIcon? = name?.let { byName[it] }

    /** Name first, then search terms; accents and case ignored ("lectura" finds "leer"'s icons too). */
    fun search(query: String, limit: Int = 60): List<FaIcon> {
        val words = fold(query).split(' ').filter { it.isNotBlank() }
        if (words.isEmpty()) return suggested.mapNotNull(::find)
        return all.asSequence()
            .filter { icon -> words.all { word -> icon.name.contains(word) || icon.terms.contains(word) } }
            .sortedBy { icon -> if (icon.name.startsWith(words.first())) 0 else 1 }
            .take(limit)
            .toList()
    }

    private fun fold(text: String): String =
        Normalizer.normalize(text.lowercase(), Normalizer.Form.NFD).replace(Regex("\\p{Mn}+"), "")
}

/** A Font Awesome icon as a glyph, sized in dp so it ignores the system font scale like an icon should. */
@Composable
fun FaGlyph(
    icon: FaIcon,
    color: Color,
    modifier: Modifier = Modifier,
    size: Dp = 22.dp,
) {
    val fontSize: TextUnit = with(LocalDensity.current) { size.toSp() } // Dp.toSp already undoes the font scale
    Text(
        text = icon.glyph,
        modifier = modifier,
        color = color,
        fontFamily = FaIcons.FontFamily,
        fontSize = fontSize,
        lineHeight = fontSize,
        textAlign = TextAlign.Center,
    )
}



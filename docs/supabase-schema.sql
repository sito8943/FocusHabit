-- Focus Habit backend (shared by the web app habbit-tracker and this Android app).
-- Inferred from the web's src/shared/lib/supabase/database.types.ts: the tables did not
-- exist in the project (2026-11-22: `relation "public.habits" does not exist`).
-- Run once in Supabase → SQL Editor.

create table if not exists public.habits (
  id          bigint generated by default as identity primary key,
  code        text        not null check (code ~ '^[A-Z0-9]{4}$'),
  name        text        not null check (length(trim(name)) > 0),
  color       text        not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  deleted_at  timestamptz
);

create index if not exists habits_code_idx on public.habits (code) where deleted_at is null;

create table if not exists public.habit_logs (
  id          bigint generated by default as identity primary key,
  habit_id    bigint      not null references public.habits (id) on delete cascade,
  log_date    date        not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  deleted_at  timestamptz
);

-- One active log per habit and day. Both clients already avoid duplicates; this enforces it.
create unique index if not exists habit_logs_one_active_per_day
  on public.habit_logs (habit_id, log_date) where deleted_at is null;

create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists habits_touch on public.habits;
create trigger habits_touch before update on public.habits
  for each row execute function public.touch_updated_at();

drop trigger if exists habit_logs_touch on public.habit_logs;
create trigger habit_logs_touch before update on public.habit_logs
  for each row execute function public.touch_updated_at();

-- No Supabase Auth: the apps use the anon key and scope everything by the 4-char code.
-- These policies keep that model (anyone with the anon key can read/write; no hard deletes).
alter table public.habits enable row level security;
alter table public.habit_logs enable row level security;

create policy "anon select habits" on public.habits for select to anon using (true);
create policy "anon insert habits" on public.habits for insert to anon with check (true);
create policy "anon update habits" on public.habits for update to anon using (true) with check (true);

create policy "anon select logs" on public.habit_logs for select to anon using (true);
create policy "anon insert logs" on public.habit_logs for insert to anon with check (true);
create policy "anon update logs" on public.habit_logs for update to anon using (true) with check (true);
